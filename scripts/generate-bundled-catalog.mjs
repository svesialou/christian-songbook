#!/usr/bin/env node
import { readFile, writeFile } from 'node:fs/promises';

const DEFAULT_INPUT = 'seed/notion-youth-songbook/songs.staging.json';
const DEFAULT_OUTPUT = 'src/data/bundledCatalog.generated.ts';

const args = parseArgs(process.argv.slice(2));
const input = args.input || DEFAULT_INPUT;
const output = args.output || DEFAULT_OUTPUT;
const payload = JSON.parse(await readFile(input, 'utf8'));

if (!Array.isArray(payload?.songs)) {
  throw new Error('Bundled catalog input must contain songs array.');
}

const songs = payload.songs.map(toSong).sort((a, b) => a.number - b.number || a.title.localeCompare(b.title, 'ru'));
const source = String(payload.sourceUrl || payload.source || input).replace(/\*\//g, '* /');

await writeFile(
  output,
  [
    "import { Song } from '../types/song';",
    '',
    '// Generated by scripts/generate-bundled-catalog.mjs. Do not edit manually.',
    `// Source: ${source}`,
    `export const bundledCatalog: Song[] = ${JSON.stringify(songs, null, 2)};`,
    '',
  ].join('\n'),
  'utf8',
);

process.stdout.write(`Generated ${songs.length} bundled songs into ${output}\n`);

function parseArgs(items) {
  const parsed = {};
  for (let index = 0; index < items.length; index += 1) {
    const item = items[index];
    if (item === '--input') parsed.input = items[++index];
    else if (item === '--output') parsed.output = items[++index];
    else throw new Error(`Unknown argument: ${item}`);
  }
  return parsed;
}

function toSong(song, index) {
  const number = positiveInteger(song.oldNumber) || index + 1;
  const title = stringValue(song.resolvedTitle) || stringValue(song.observedTitle) || `Песня ${number}`;
  const rows = splitLines(song.lyrics);
  const chordRows = splitLines(song.chords).map(splitChordLine);

  return {
    id: `notion-youth-${number}`,
    number,
    title,
    category: stringValue(song.category) || 'Разное',
    defaultKey: stringValue(song.defaultKey) || undefined,
    playback: undefined,
    verses: [
      {
        rows,
        chords: rows.map((_, rowIndex) => chordRows[rowIndex] || []),
      },
    ],
  };
}

function positiveInteger(value) {
  const parsed = Number(value);
  return Number.isInteger(parsed) && parsed > 0 ? parsed : null;
}

function stringValue(value) {
  return typeof value === 'string' && value.trim().length > 0 ? value.trim() : '';
}

function splitLines(value) {
  if (typeof value !== 'string') return [];
  return value
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter(Boolean);
}

function splitChordLine(line) {
  return line.split(/\s+/).map((chord) => chord.trim()).filter(Boolean);
}
