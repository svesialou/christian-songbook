export function categorizeSong(song, fallback = 'Разное') {
  const current = stringValue(song.category);
  if (current && current !== YOUTH_CATEGORY && validCategories.has(current)) {
    return current;
  }

  const haystack = normalizeText([
    song.resolvedTitle,
    song.observedTitle,
    song.title,
    song.lyrics,
  ].filter(Boolean).join('\n'));

  for (const [category, needles] of rules) {
    if (needles.some((needle) => haystack.includes(normalizeText(needle)))) {
      return category;
    }
  }

  const normalizedFallback = stringValue(fallback);
  return normalizedFallback && normalizedFallback !== YOUTH_CATEGORY && validCategories.has(normalizedFallback)
    ? normalizedFallback
    : 'Разное';
}

function normalizeText(value) {
  return String(value || '')
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/\s+/g, ' ')
    .trim();
}

function stringValue(value) {
  return typeof value === 'string' && value.trim().length > 0 ? value.trim() : '';
}
